"""Pydantic v2 Contract Schemas for Model-to-Agent Integration.

Enforces zero-hallucination data transfer between prescriptive ML models
and downstream LLM agentic retention workflows.
"""

from typing import Any, Dict, List, Literal, Optional
from pydantic import BaseModel, Field


class FeatureDriver(BaseModel):
    """TreeSHAP feature contribution contract."""
    feature_name: str
    feature_value: float
    shap_contribution: float
    direction: Literal["increases_churn_risk", "reduces_churn_risk"]


class DecisionPacket(BaseModel):
    """Structured prescriptive output packaging ML metrics and eligibility for agent consumption."""
    subscriber_id: str
    baseline_churn_prob: float = Field(..., ge=0.0, le=1.0)
    strategic_quadrant: Literal["Persuadable", "Sure_Thing", "Lost_Cause", "Sleeping_Dog"]
    recommended_action: Literal["no_action", "data_booster_15gb", "combo_discount_20pct", "qos_priority_care"]
    expected_uplift_pct: float
    uplift_confidence_lower_90: float
    uplift_confidence_upper_90: float
    eligibility_passed: bool
    eligibility_reason: str
    intervention_cost_idr: float
    expected_net_value_idr: float
    top_key_drivers: List[FeatureDriver] = Field(default_factory=list)


class AgentInterventionResponse(BaseModel):
    """Final personalized dispatch communication payload generated by Retention Agent."""
    subscriber_id: str
    channel: Literal["WhatsApp", "MyIOH_Push", "Field_Engineer_Ticket", "Holdout_No_Action"]
    guardrail_passed: bool
    guardrail_rejection_reason: Optional[str] = None
    intervention_message_id_lang: str
    technical_summary: str
    recommended_action: str
    intervention_cost_idr: float
    expected_net_value_idr: float
    source: Literal["groq_llama_70b", "deterministic_policy_fallback"]


class SubscriberFeatureInput(BaseModel):
    """Input payload for scoring a single subscriber."""
    subscriber_id: str
    tenure_months: int = Field(..., ge=0)
    monthly_arpu_idr: float = Field(..., ge=0.0)
    data_usage_gb_m1: float = Field(..., ge=0.0)
    usage_decay_ratio: float = Field(..., ge=0.0)
    drop_call_rate: float = Field(..., ge=0.0, le=100.0)
    complaint_count_90d: int = Field(..., ge=0)
    is_prepaid: int = Field(1, ge=0, le=1)
    is_annual: int = Field(0, ge=0, le=1)
    cltv_idr: Optional[float] = None


class CohortOptimizationRequest(BaseModel):
    """Request payload for cohort-level campaign optimization."""
    budget_idr: float = Field(18_000_000.0, ge=0.0)
    confidence_alpha: float = Field(0.10, ge=0.01, le=0.50)
    max_subscribers: Optional[int] = Field(None, ge=10, le=100000)


class CohortOptimizationSummary(BaseModel):
    """Summary of Stackelberg Knapsack cohort optimization."""
    budget_limit_idr: float
    budget_spent_idr: float
    budget_utilization_pct: float
    net_incremental_value_idr: float
    roi_multiple: float
    total_subscribers: int
    action_distribution: Dict[str, int]
    solver: str
    elapsed_seconds: float
